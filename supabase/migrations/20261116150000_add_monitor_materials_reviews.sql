CREATE TABLE IF NOT EXISTS monitor_material (
  id_material BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  monitor_id INTEGER NOT NULL
    REFERENCES monitor (id_monitor) ON DELETE CASCADE,
  titulo VARCHAR(200) NOT NULL,
  descricao TEXT NOT NULL DEFAULT '',
  storage_path TEXT UNIQUE,
  nome_arquivo VARCHAR(255),
  content_type VARCHAR(127),
  tamanho_bytes BIGINT,
  arquivo_enviado BOOLEAN NOT NULL DEFAULT FALSE,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT monitor_material_file_metadata_check CHECK (
    (storage_path IS NULL AND nome_arquivo IS NULL AND content_type IS NULL AND tamanho_bytes IS NULL)
    OR
    (
      storage_path IS NOT NULL
      AND nome_arquivo IS NOT NULL
      AND content_type IS NOT NULL
      AND tamanho_bytes IS NOT NULL
      AND tamanho_bytes > 0
    )
  )
);

CREATE INDEX IF NOT EXISTS monitor_material_monitor_created_idx
  ON monitor_material (monitor_id, criado_em DESC);

CREATE TABLE IF NOT EXISTS monitor_review (
  id_review BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  monitor_id INTEGER NOT NULL
    REFERENCES monitor (id_monitor) ON DELETE CASCADE,
  usuario_id INTEGER NOT NULL
    REFERENCES usuario (id_usuario) ON DELETE CASCADE,
  nota SMALLINT NOT NULL CHECK (nota BETWEEN 1 AND 5),
  comentario TEXT NOT NULL DEFAULT '',
  criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
  atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (monitor_id, usuario_id),
  CHECK (length(comentario) <= 2000)
);

CREATE INDEX IF NOT EXISTS monitor_review_monitor_created_idx
  ON monitor_review (monitor_id, criado_em DESC);

ALTER TABLE monitor_material ENABLE ROW LEVEL SECURITY;
ALTER TABLE monitor_review ENABLE ROW LEVEL SECURITY;

