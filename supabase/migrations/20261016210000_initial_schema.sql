CREATE TABLE IF NOT EXISTS usuario (
  id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  email VARCHAR(254) NOT NULL,
  senha_hash TEXT NOT NULL,
  tipo_usuario VARCHAR(20) NOT NULL
    CHECK (tipo_usuario IN ('aluno', 'monitor')),
  criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS usuario_email_lower_uidx
  ON usuario (lower(email));

CREATE TABLE IF NOT EXISTS materias (
  id_materia INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  assunto TEXT
);

CREATE UNIQUE INDEX IF NOT EXISTS materias_nome_lower_uidx
  ON materias (lower(nome));

CREATE TABLE IF NOT EXISTS monitor (
  id_monitor INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER NOT NULL UNIQUE
    REFERENCES usuario (id_usuario) ON DELETE CASCADE,
  materia_id INTEGER
    REFERENCES materias (id_materia) ON DELETE SET NULL,
  nota NUMERIC(4, 2),
  meet_link VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS monitor_materias (
  monitor_id INTEGER NOT NULL
    REFERENCES monitor (id_monitor) ON DELETE CASCADE,
  materia_id INTEGER NOT NULL
    REFERENCES materias (id_materia) ON DELETE CASCADE,
  PRIMARY KEY (monitor_id, materia_id)
);

CREATE TABLE IF NOT EXISTS usuario_configuracao (
  usuario_id INTEGER PRIMARY KEY
    REFERENCES usuario (id_usuario) ON DELETE CASCADE,
  biografia TEXT,
  meet_link VARCHAR(500),
  atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS calendario (
  id_calendario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  data_hora TIMESTAMP NOT NULL,
  titulo VARCHAR(200) NOT NULL DEFAULT 'Aula agendada',
  monitor_id INTEGER NOT NULL
    REFERENCES monitor (id_monitor) ON DELETE CASCADE,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS calendario_monitor_data_idx
  ON calendario (monitor_id, data_hora);

ALTER TABLE usuario ENABLE ROW LEVEL SECURITY;
ALTER TABLE materias ENABLE ROW LEVEL SECURITY;
ALTER TABLE monitor ENABLE ROW LEVEL SECURITY;
ALTER TABLE monitor_materias ENABLE ROW LEVEL SECURITY;
ALTER TABLE usuario_configuracao ENABLE ROW LEVEL SECURITY;
ALTER TABLE calendario ENABLE ROW LEVEL SECURITY;
